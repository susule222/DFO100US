// IsEmblemTemplate reports whether template id is a US100 [avatar emblem] item.
func IsEmblemTemplate(id uint32) bool {
	lo, hi := 0, len(us100EmblemBands)-1
	for lo <= hi {
		mid := (lo + hi) / 2
		band := us100EmblemBands[mid]
		if id < band[0] {
			hi = mid - 1
		} else if id > band[1] {
			lo = mid + 1
		} else {
			return true
		}
	}
	return false
}
